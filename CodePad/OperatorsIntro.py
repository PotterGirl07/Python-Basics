#Arithmetic operator

#int/float
print(10.89+10)
print(20-20)
print(123*123)
print(122/6)
print(122//6)#floor(keeps whole #, discards decimal)
print(13%2)#remainder(remaining value after division)

# + and * has special purpose when it comes to strings
x="1"
y="2"
print(x+y)#concatentaion(join strings)
print(x*5)

#comparison
print(10>5)#greater than
print(5<2)#less than
print(18>=18)#greater than or equal to
print(12<=3)#less than or equal to
print(7==7)#equal to
print(67!=67)#not equal to

#assignment operator
s=10 #assigning value 10 to s variable
print(s)

#logical operator
n=12
#'or' says true if any one of the statements are true
print(n<1 or n<20)
#'and' says true if all statements are true
print(n<1 and n<20)
#not
print(not True)
print(not False)