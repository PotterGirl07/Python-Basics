#sunny, rainy, cloudy, snowy

weather=input("Enter your weather: ")
if weather=="sunny":
    print("Wear sunscreen, don't get burnt!")
elif weather=="rainy":
    print("Don't forget to keep an umbrella handy.")
elif weather=="cloudy":
    print("There may be a storm incoming, don't get struck by lightning!")
elif weather=="snowy":
    print("Go make a snowman, but don't become one!")
else:
    print("Dress accordingly to the weather!")