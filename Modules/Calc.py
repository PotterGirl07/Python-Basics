def AddNums(n1, n2):
    result = n1 + n2
    return result

def SubNums(n1, n2):
    result = n1 - n2
    return result

def DivNums(n1, n2):
    result = n1 / n2
    return result

def MulNums(n1, n2):
    result = n1 * n2
    return result

print("Addition:", AddNums(10, 5))
print("Subtraction:", SubNums(10, 5))
print("Division:", DivNums(10, 5))
print("Multiplication:", MulNums(10, 5))