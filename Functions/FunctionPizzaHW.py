def BakePizza(base, topping):
    print("Steps to bake a pizza:")
    print(f"1. Prepare the {base} base and spread tomato sauce")
    print(f"2. Add the cheese and {topping} as the topping.")
    print("3. Bake the pizza in the oven")
    print("4. Slice and enjoy!")
    print("~" *50)


BakePizza("thick crust", "black olives")
BakePizza("hand-tossed crust", "chicken")
BakePizza("thin crust", "jalapenos")
