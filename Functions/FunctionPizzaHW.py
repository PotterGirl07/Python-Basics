def BakePizza(base, topping):
    print("Steps to bake a pizza:")
    print(f"1. Prepare the {base} base")
    print(f"2. Spread tomato sauce on the base")
    print(f"3. Add {topping} as the topping")
    print("4. Add cheese on the top")
    print("5. Bake the pizza in the oven")
    print("6. Slice and enjoy!")
    print("~" *50)


BakePizza("Thick crust", "black Olives")
BakePizza("Thin crust", "jalapenos")
BakePizza("Hand-tossed crust", "chicken")